"""Save the height above sea level along every day's walk into the planner (the elevation markers and the squirrels' badge).

Samples each day's walking path (the same geometry the app draws, `llAt` with walking paths on) every 100 m of
itinerary km, and reads the height from GSI's 10 m elevation tiles (国土地理院 標高タイル dem_png, zoom 14,
bilinear). Tiles are cached in .cache/dem/. Re-run after tools/build_paths.py or after moving a stop.

Writes data/elevation.json and the ELEV block in src/planner.html (between the ELEV markers). Then run
python3 tools/build_live.py, the sweeps, and commit + push.

Run from the repo root:   python3 tools/build_elev.py
"""
import io, json, math, re, sys, time, urllib.request
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PLANNER = ROOT / "src/planner.html"
OUT = ROOT / "data/elevation.json"
CACHE = ROOT / ".cache/dem"; CACHE.mkdir(parents=True, exist_ok=True)
Z, STEP = 14, 0.1
TILES = {}

def tile(x, y):
    if (x, y) in TILES: return TILES[(x, y)]
    f = CACHE / f"{Z}_{x}_{y}.png"
    if not f.exists():
        url = f"https://cyberjapandata.gsi.go.jp/xyz/dem_png/{Z}/{x}/{y}.png"
        for i in range(4):
            try:
                with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "nakasendo-route-planner/1.0"}), timeout=60) as r:
                    f.write_bytes(r.read()); break
            except Exception as e:
                if getattr(e, "code", None) == 404: f.write_bytes(b""); break   # sea / no data
                print(f"  … {url} failed ({e})", file=sys.stderr); time.sleep(2 * (i + 1))
        time.sleep(0.05)
    TILES[(x, y)] = Image.open(io.BytesIO(f.read_bytes())).convert("RGB").load() if f.stat().st_size else None
    return TILES[(x, y)]

def px_height(px, py):
    t = tile(px // 256, py // 256)
    if t is None: return None
    r, g, b = t[px % 256, py % 256]; v = (r << 16) + (g << 8) + b
    return None if v == 1 << 23 else (v if v < 1 << 23 else v - (1 << 24)) * 0.01

def height(la, lo):
    n = 2 ** Z * 256
    fx = (lo + 180) / 360 * n; s = math.sin(math.radians(la)); fy = (0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)) * n
    x0, y0 = int(fx - 0.5), int(fy - 0.5); ax, ay = fx - 0.5 - x0, fy - 0.5 - y0
    q = [[px_height(x0 + i, y0 + j) for i in (0, 1)] for j in (0, 1)]
    vals = [v for row in q for v in row if v is not None]
    if not vals: return None
    if len(vals) < 4: return sum(vals) / len(vals)
    return (q[0][0] * (1 - ax) + q[0][1] * ax) * (1 - ay) + (q[1][0] * (1 - ax) + q[1][1] * ax) * ay

def samples_from_planner():
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        b = p.chromium.launch(); pg = b.new_page()
        pg.route("https://**/*", lambda r: r.abort())
        pg.goto(PLANNER.as_uri())
        out = pg.evaluate(f"""() => {{ S.paths = "walk"; const out = {{}};
          Object.values(DAYS).forEach(d => {{ const n = Math.round(total(d) / {STEP});
            out[d.id] = {{total: total(d), up: d.pts.reduce((a, p) => a + (p.up || 0), 0), ll: Array.from({{length: n + 1}}, (_, i) => llAt(d, Math.min(i * {STEP}, total(d))))}}; }});
          return out; }}""")
        b.close(); return out

def main():
    days = {}
    for k, d in samples_from_planner().items():
        h = [height(*ll) for ll in d["ll"]]
        for i, v in enumerate(h):            # fill any gap from the neighbours
            if v is None: h[i] = next((h[j] for j in range(i - 1, -1, -1) if h[j] is not None), None) or next((x for x in h[i:] if x is not None), 0)
        h = [round(v) for v in h]
        sm = [sum(h[max(0, i - 2):i + 3]) / len(h[max(0, i - 2):i + 3]) for i in range(len(h))]   # light smoothing for the climb total only
        up = sum(max(0, sm[i + 1] - sm[i]) for i in range(len(sm) - 1))
        days[k] = h
        print(f"{k}: {d['total']:5.1f} km, {len(h)} samples, {min(h)}–{max(h)} m, high point {max(h)} m at {h.index(max(h)) * STEP:.1f} km, "
              f"climb ≈{up:.0f} m (itinerary up {d['up']} m)")
    data = {"step": STEP, "src": "GSI 10 m DEM (国土地理院 標高タイル)", "days": days}
    OUT.write_text(json.dumps(data, separators=(",", ":"), ensure_ascii=False))
    block = ("/* ELEV:BEGIN generated by tools/build_elev.py (heights in m every `step` km of each day; GSI elevation tiles). Don't edit by hand. */\n"
             f"const ELEV = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n/* ELEV:END */")
    src = PLANNER.read_text(encoding="utf-8"); pat = re.compile(r"/\* ELEV:BEGIN.*?/\* ELEV:END \*/", re.S)
    assert len(pat.findall(src)) == 1, "ELEV markers not found exactly once in src/planner.html"
    PLANNER.write_text(pat.sub(lambda m: block, src), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and the ELEV block ({len(block)} bytes)")

if __name__ == "__main__": main()
